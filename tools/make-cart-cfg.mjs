#!/usr/bin/env node
// Generate the banked C cartridge linker configs.
//
//   node tools/make-cart-cfg.mjs            rewrite all four
//   node tools/make-cart-cfg.mjs --check    exit 1 if any is stale
//
// These are NOT copies of 6502-ASM's, and that is the whole point of having a
// second generator. 6502-ASM's banked configs describe a bare cartridge —
// banks, a fixed region, vectors. A C cartridge also needs everything
// 6502-16K.cfg here already carries: FEATURES, SYMBOLS, a ZP and a RAM area,
// the DATA-load-into-RAM split and the CONDES tables. So a C banked config is
// the assembly banked layout PLUS all of that, with three placement decisions
// the assembly version never has to make. They are spelt out in each generated
// file, because each of them looks arbitrary and none of them is.
//
// The mapper is 6502-VCS PLAN.md §2; the bank layout follows 6502-CRT's
// tools/make-cart-cfg.mjs and must not diverge from it. ld65 writes each
// MEMORY area that names a file to that file in declaration order, and that
// order IS the flash's linear layout.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

const BANK_SIZE = 0x2000
const FIXED_SIZE = 0x1FFA // $E000-$FFF9; the vectors take the last six bytes

/**
 * The four flash cart targets of 6502-VCS PLAN.md §1.
 *
 * `chips` is 1, or 2 for a -1M cart, whose second chip is selected by bit 6 of
 * the bank register and is the second half of the file.
 */
const TARGETS = [
  { target: '128K', bytes: 0x020000, part: 'SST39SF010A', chips: 1 },
  { target: '256K', bytes: 0x040000, part: 'SST39SF020A', chips: 1 },
  { target: '512K', bytes: 0x080000, part: 'SST39SF040', chips: 1 },
  { target: '1M', bytes: 0x100000, part: 'SST39SF040 x2', chips: 2 }
]

const hex2 = (n) => n.toString(16).toUpperCase().padStart(2, '0')
const hex4 = (n) => '$' + n.toString(16).toUpperCase().padStart(4, '0')

function banksFor({ bytes, chips }) {
  const perChip = bytes / chips / BANK_SIZE
  const fixed = perChip - 1 // the primary chip's last 8 KB is never switchable
  const primary = [...Array(fixed).keys()]
  const secondary = chips === 2 ? [...Array(perChip).keys()].map((b) => 0x40 | b) : []
  return { fixed, primary, secondary }
}

function generate(spec) {
  const { target, bytes, part, chips } = spec
  const { fixed, primary, secondary } = banksFor(spec)

  const area = (name, start, size, comment) =>
    `  ${(name + ':').padEnd(9)}file = %O, start = ${hex4(start)}, size = ${hex4(size)}, ` +
    `fill = yes, fillval = $FF;` + (comment ? `  # ${comment}` : '')

  const memory = [
    ...primary.map((b, i) =>
      area(`BANK${hex2(b)}`, 0xC000, BANK_SIZE, i === 0 ? 'the switchable window, $C000-$DFFF' : '')
    ),
    area('FIXED', 0xE000, FIXED_SIZE, `always visible, whatever the register holds (bank $${hex2(fixed)})`),
    area('VECTORS', 0xFFFA, 0x0006, 'NMI, RESET, IRQ — never bankable'),
    ...secondary.map((b, i) =>
      area(`BANK${hex2(b)}`, 0xC000, BANK_SIZE, i === 0 ? 'U2, the file’s second half' : '')
    )
  ]

  const bankSegments = [...primary, ...secondary].map(
    (b) => `  ${('BANK' + hex2(b) + ':').padEnd(10)}load = ${('BANK' + hex2(b) + ',').padEnd(10)}type = ro,  optional = yes;`
  )

  const usable = [...primary, ...secondary]
  const usableText =
    chips === 2 ? `$00-$${hex2(fixed - 1)} and $40-$7F` : `$00-$${hex2(fixed - 1)}`

  // The banner box is sized to its title, the way 6502-16K.cfg's is.
  const title = `     AC6502 C FLASH CART ${target} — LINKER CONFIG    `
  const rule = ' '.repeat(title.length)

  return `# ***${rule}***
# ***${title}***
# ***${rule}***
#
# A banked cartridge for the AC6502 Flash Cart: ${part}, ${bytes.toLocaleString()} bytes.
# Generated by tools/make-cart-cfg.mjs — do not edit.  \`make check-configs\`
# fails on a stale copy.
#
#   THE MAPPER (6502-VCS PLAN.md §2)
#   --------------------------------
#   $C000-$DFFF  8 KB switchable window.  Which bank appears here is the value
#                last written to the bank register.
#   $E000-$FFFF  8 KB fixed region — the primary chip's last 8 KB, always, and
#                the only place the reset and interrupt vectors can live.
#
#   The bank register is write-only at ANY address in $E000-$FFFF, it cannot be
#   read back, and RESB clears it to 0.  A write there latches the register and
#   reaches no flash.  \`set_bank()\` in 6502.h is the way to write it.
#
#   \`#pragma rodata-name (push, "BANK07")\` is reached with \`set_bank(0x07)\`:
#   the segment name IS the value you write.  Usable bank values here:
#   ${usableText} (${usable.length} banks, ${usable.length * BANK_SIZE / 1024} KB).
#   $${hex2(fixed)} is the fixed bank and has no BANK segment: it is FIXED.
#
#   THE BUDGET, WHICH IS THE THING TO READ FIRST
#   --------------------------------------------
#   $C000-$FFF9  16,378 bytes   what 6502-16K.cfg gives a C program
#   $E000-$FFF9   ${FIXED_SIZE.toLocaleString()} bytes   what this gives it
#
#   A C cartridge that does nothing special has LESS room here than the fixed
#   build, not more: 8 KB of code instead of 16.  You move to a banked cart for
#   the banks, not for the code space.  The banks hold what you put in them
#   deliberately, and for C that means large \`const\` data — see the README.
#
#   THREE PLACEMENTS THAT LOOK ARBITRARY AND ARE NOT
#   ------------------------------------------------
#   1. STARTUP loads into FIXED, not into a bank.  6502-16K.cfg puts it at
#      $C000 and points RESET at it; here $C000 is a *bank*, whichever one the
#      register happens to hold.  At reset that is bank 0, so it would work by
#      accident and break the moment anyone reorganised the banks.
#
#   2. DATA's load image is in FIXED — \`load = FIXED, run = RAM\` — with no
#      exceptions.  crt0cart.s calls copydata at reset to move DATA from ROM to
#      RAM.  If the load image sat in a bank, copydata would read whatever bank
#      the register selects.  That is bank 0 at reset, so again it works until
#      somebody puts something else in bank 0.
#
#   3. CODE, RODATA, LOWCODE and ONCE load into FIXED too.  A \`#pragma
#      code-name\` into a bank compiles, links, and crashes when the caller's
#      bank is not the callee's; there is no diagnostic for it anywhere in the
#      toolchain.  The README says so at length.
#
#   WHY fillval = $FF
#   -----------------
#   $FF is what an erased flash chip holds, so every unused byte already
#   matches the chip after a chip erase and \`6502-flash program\` skips the
#   sector outright.  6502-16K.cfg keeps fillval = $00: a 28C256 has no erased
#   state to exploit.
#
#   WHY THE DECLARATION ORDER MATTERS
#   ---------------------------------
#   ld65 writes each MEMORY area that names a file to that file in the order
#   the areas are declared, and that order IS the flash's linear layout.  Do
#   not reorder these blocks.  ZP and RAM name no file and describe where the
#   program lives at runtime, so they sit out of the way at the top.
#
#   See the 6502-DOCS chapter *Bigger cartridges*, and this repository's README
#   section *Banked cartridges*.

FEATURES {
  CONDES: type    = constructor,
          label   = __CONSTRUCTOR_TABLE__,
          count   = __CONSTRUCTOR_COUNT__,
          segment = ONCE;
  CONDES: type    = destructor,
          label   = __DESTRUCTOR_TABLE__,
          count   = __DESTRUCTOR_COUNT__,
          segment = RODATA;
  CONDES: type    = interruptor,
          label   = __INTERRUPTOR_TABLE__,
          count   = __INTERRUPTOR_COUNT__,
          segment = RODATA,
          import  = __CALLIRQ__;
}

SYMBOLS {
  __STARTUP__:    type = import;                # pull crt0cart out of the link
  __STACKSIZE__:  type = weak, value = $0800;   # 2 KB C parameter stack
  __STACKSTART__: type = weak, value = $8000;   # first byte past usable RAM
}

MEMORY {
  # Not written to the file — these describe where the program lives at
  # runtime, and RAM comes up as whatever it comes up as.
  ZP:       file = "", define = yes, start = $003A, size = $00C6;
  RAM:      file = "", define = yes, start = $0800,
                                     size = __STACKSTART__ - __STACKSIZE__ - $0800;

  # The flash image, in the order the chip holds it.
${memory.join('\n')}
}

SEGMENTS {
  ZEROPAGE: load = ZP,      type = zp;
  STARTUP:  load = FIXED,   type = ro;                    # crt0cart, at $E000
  LOWCODE:  load = FIXED,   type = ro,  optional = yes;
  ONCE:     load = FIXED,   type = ro,  optional = yes;   # constructors
  CODE:     load = FIXED,   type = ro;
  RODATA:   load = FIXED,   type = ro;
  DATA:     load = FIXED,   run  = RAM, type = rw, define = yes;
  BSS:      load = RAM,     type = bss, define = yes;
  VECTORS:  load = VECTORS, type = ro;

  # The banks.  optional = yes throughout, so a cart that uses four of them
  # need not declare the other ${usable.length - 4}.
${bankSegments.join('\n')}
}
`
}

const files = TARGETS.map((spec) => ({
  name: `6502-${spec.target}.cfg`,
  text: generate(spec),
  bytes: spec.bytes
}))

// The size each config must produce is arithmetic, not a promise: assert it
// here so a bad table is caught before ld65 quietly emits a short file.
for (const spec of TARGETS) {
  const { primary, secondary } = banksFor(spec)
  const total = (primary.length + secondary.length + 1) * BANK_SIZE
  if (total !== spec.bytes) {
    console.error(`${spec.target}: banks total ${total} bytes, expected ${spec.bytes}`)
    process.exit(1)
  }
}

const check = process.argv.includes('--check')
let stale = 0

for (const file of files) {
  const path = join(ROOT, file.name)
  if (check) {
    let current = null
    try {
      current = readFileSync(path, 'utf8')
    } catch {
      /* missing counts as stale */
    }
    if (current !== file.text) {
      console.error(`${file.name} is stale`)
      stale++
    }
  } else {
    writeFileSync(path, file.text)
    console.log(`${file.name}  ${file.bytes.toLocaleString()} bytes when linked`)
  }
}

if (check) {
  if (stale) {
    console.error('Run `node tools/make-cart-cfg.mjs` to regenerate.')
    process.exit(1)
  }
  console.log('All four cartridge configs are up to date.')
}
